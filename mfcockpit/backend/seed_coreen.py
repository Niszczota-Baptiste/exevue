def _dlg(titre, lignes):
    """Dialogue : `kr` = les répliques KR, `fr` = la traduction, ligne à ligne."""
    kr = "\n".join(f"{qui} : {k}" for qui, k, _f in lignes)
    fr = "\n".join(f"{qui} : {f}" for qui, _k, f in lignes)
    return (D, kr, "", fr, titre, titre)


