def date_debut_programme(aujourd_hui=None) -> _dt.date:
    """Lundi de la semaine du 18 août de l'année de référence.

    L'année de référence est l'année en cours tant qu'on n'a pas dépassé la fin
    du programme (9 semaines), sinon l'année suivante — ainsi le programme est
    toujours devant soi au premier lancement.
    """
    today = aujourd_hui or _dt.date.today()
    annee = today.year
    depart = _dt.date(annee, 8, 18)
    depart -= _dt.timedelta(days=depart.weekday())   # recule au lundi
    if today > depart + _dt.timedelta(weeks=9):
        depart = _dt.date(annee + 1, 8, 18)
        depart -= _dt.timedelta(days=depart.weekday())
    return depart


def seed(c, aujourd_hui=None):
    """Insère les 9 semaines, leurs items, cartes et exercices. Idempotent."""
    if c.execute("SELECT COUNT(*) FROM kr_semaine").fetchone()[0]:
        return
    debut = date_debut_programme(aujourd_hui)

    for sem in SEMAINES:
        d0 = debut + _dt.timedelta(weeks=sem["numero"] - 1)
        d1 = d0 + _dt.timedelta(days=6)
        cur = c.execute(
            "INSERT INTO kr_semaine(numero, theme, date_debut, date_fin, "
            "objectifs_json, note_culture) VALUES (?,?,?,?,?,?)",
            (sem["numero"], sem["theme"], d0.isoformat(), d1.isoformat(),
             json.dumps(sem["objectifs"], ensure_ascii=False),
             sem["culture"]))
        semaine_id = cur.lastrowid

        ordre = 0
        items = list(sem["items"]) + [_dlg(t, lignes)
                                      for t, lignes in sem["dialogues"]]
        for (typ, kr, romaja, fr, ex_kr, ex_fr) in items:
            ordre += 1
            icur = c.execute(
                "INSERT INTO kr_item(semaine_id, type, kr, romaja, fr, "
                "exemple_kr, exemple_fr, tags, source, ordre) "
                "VALUES (?,?,?,?,?,?,?,?,'programme',?)",
                (semaine_id, typ, kr, romaja, fr, ex_kr, ex_fr,
                 sem["theme"], ordre))
            item_id = icur.lastrowid
            if typ not in TYPES_CARTES:
                continue
            # Deux cartes : KR->FR active, FR->KR débloquée après 3 réussites.
            due = _dt.datetime.combine(d0, _dt.time(4, 0)).timestamp()
            c.execute(
                "INSERT OR IGNORE INTO kr_carte(item_id, direction, due, "
                "interval, ease, reps, lapses, suspendu) "
                "VALUES (?, 'kr_fr', ?, 0, 2.5, 0, 0, 0)", (item_id, due))
            c.execute(
                "INSERT OR IGNORE INTO kr_carte(item_id, direction, due, "
                "interval, ease, reps, lapses, suspendu) "
                "VALUES (?, 'fr_kr', ?, 0, 2.5, 0, 0, 1)", (item_id, due))

        # ---- exercices de la semaine ----
        for typ, titre, contenu, duree in (
            ("reco", f"Reconnaissance KR→FR · S{sem['numero']}",
             {"auto": True, "qcm": 4}, 5),
            ("prod", f"Production FR→KR · S{sem['numero']}",
             {"auto": True, "qcm": 4}, 5),
            ("trous", f"Texte à trous · S{sem['numero']}",
             {"phrases": [{"phrase": p, "reponse": r, "indice": i}
                          for p, r, i in sem["trous"]]}, 5),
            ("roleplay", sem["roleplay"]["titre"], sem["roleplay"], 8),
            ("ecoute", f"Écoute · S{sem['numero']}",
             {"auto": True, "qcm": 4, "lang": "ko-KR"}, 5),
        ):
            c.execute(
                "INSERT INTO kr_exercice(semaine_id, type, titre, "
                "contenu_json, duree_cible_min) VALUES (?,?,?,?,?)",
                (semaine_id, typ, titre,
                 json.dumps(contenu, ensure_ascii=False), duree))
